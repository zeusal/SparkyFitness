// Generates src/data/tokens.ts and src/data/icons.ts from the app sources.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const APP = process.argv[2];
const OUT = process.argv[3];
const css = fs.readFileSync(path.join(APP, 'global.css'), 'utf8');
const design = fs.readFileSync(path.join(APP, 'DESIGN.md'), 'utf8');
const iconSrc = fs.readFileSync(path.join(APP, 'src/components/Icon.tsx'), 'utf8');

function hslToRgb(h, s, l) {
  s /= 100; l /= 100;
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0), f(8), f(4)];
}
const toHex = (rgb) => '#' + rgb.map((x) => Math.round(x * 255).toString(16).padStart(2, '0')).join('').toUpperCase();

// --- tokens from global.css
let variant = 'root';
const vals = { root: {}, light: {}, dark: {}, amoled: {} };
for (const line of css.split('\n')) {
  const v = line.match(/@variant\s+(\w+)/);
  if (v) { variant = v[1]; continue; }
  const m = line.match(/^\s*(--[\w-]+):\s*([^;]+);/);
  if (!m) continue;
  const [, name, value] = m;
  const h = value.match(/hsla?\(\s*([\d.]+),\s*([\d.]+)%,\s*([\d.]+)%(?:,\s*([\d.]+))?\)/);
  vals[variant][name] = h ? { hex: toHex(hslToRgb(+h[1], +h[2], +h[3])), a: h[4] ? +h[4] : 1 } : { raw: value.trim() };
}

// --- role names, groups and usage from DESIGN.md section 2 tables
const sec2 = design.split('## 2. Color Palette & Roles')[1].split('## 3.')[0];
let group = '';
const roles = {};
for (const line of sec2.split('\n')) {
  const g = line.match(/^### (.+)/);
  if (g) { group = g[1].trim(); continue; }
  if (!line.startsWith('|') || line.includes('---') || /\|\s*Role\s*\|/.test(line) || /\|\s*Token\s*\|/.test(line)) continue;
  const cells = line.split('|').slice(1, -1).map((c) => c.trim());
  if (cells.length < 5) continue;
  const [role, tokenCell, , , usage] = cells;
  const toks = new Set();
  for (const t of tokenCell.matchAll(/--color-[\w-]+/g)) toks.add(t[0]);
  for (const t of tokenCell.matchAll(/`(?:bg|text|border)-([\w-]+)`/g)) toks.add('--color-' + t[1]);
  for (const t of toks) {
    if (vals.light[t] && !roles[t]) roles[t] = { name: role, group, usage: usage.replace(/`/g, '').replace(/\s+/g, ' ') };
  }
}

const colors = Object.keys(vals.light).filter((k) => k.startsWith('--color-')).map((token) => {
  const r = roles[token] || { name: token.replace('--color-', ''), group: 'Other', usage: '' };
  const pick = (v) => vals[v][token] || vals.dark[token];
  return {
    token,
    name: r.name,
    group: r.group,
    usage: r.usage.length > 180 ? r.usage.slice(0, 177) + '…' : r.usage,
    light: pick('light'),
    dark: pick('dark'),
    amoled: pick('amoled'),
  };
});
const missing = colors.filter((c) => c.group === 'Other').map((c) => c.token);
if (missing.length) console.error('WARN no role for', missing);

const spacing = Object.entries(vals.root).filter(([k]) => k.startsWith('--spacing')).map(([k, v]) => ({ token: k, px: parseInt(v.raw) }));
const radii = Object.entries(vals.root).filter(([k]) => k.startsWith('--radius')).map(([k, v]) => ({ token: k, px: parseInt(v.raw) }));

fs.mkdirSync(path.join(OUT, 'src/data'), { recursive: true });
fs.writeFileSync(path.join(OUT, 'src/data/tokens.ts'),
`// GENERATED by scripts/gen-data.mjs from SparkyFitnessMobile/global.css and DESIGN.md. Do not edit by hand.
export interface ColorValue { hex: string; a: number }
export interface ColorToken { token: string; name: string; group: string; usage: string; light: ColorValue; dark: ColorValue; amoled: ColorValue }
export const COLOR_TOKENS: ColorToken[] = ${JSON.stringify(colors, null, 2)};
export const SPACING_TOKENS: { token: string; px: number }[] = ${JSON.stringify(spacing)};
export const RADIUS_TOKENS: { token: string; px: number }[] = ${JSON.stringify(radii)};
`);
console.error(`colors=${colors.length} spacing=${spacing.length} radii=${radii.length}`);

// --- icons from Icon.tsx ICON_MAP (Android Ionicons glyphs, MIT licensed)
const mapBody = iconSrc.slice(iconSrc.indexOf('const ICON_MAP = {'), iconSrc.indexOf('} as const'));
const icons = {};
for (const m of mapBody.matchAll(/^\s*'?([\w-]+)'?:\s*\{\s*sf:\s*'([^']+)',\s*ion:\s*'([^']+)'/gm)) icons[m[1]] = { sf: m[2], ion: m[3] };
const cache = path.join(OUT, '.cache/svg');
const svgs = {};
for (const [name, { ion }] of Object.entries(icons)) {
  const file = path.join(cache, ion + '.svg');
  if (!fs.existsSync(file)) {
    try { execFileSync('curl', ['-sSf', '-o', file, `https://unpkg.com/ionicons@7.4.0/dist/svg/${ion}.svg`]); }
    catch { console.error('WARN missing svg', ion); continue; }
  }
  let svg = fs.readFileSync(file, 'utf8').replace(/<title>.*?<\/title>/g, '').replace(/\sclass="[^"]*"/g, '');
  svgs[name] = { sf: icons[name].sf, ion, svg };
}
fs.writeFileSync(path.join(OUT, 'src/data/icons.ts'),
`// GENERATED by scripts/gen-data.mjs from SparkyFitnessMobile/src/components/Icon.tsx.
// Glyphs: Ionicons 7.4.0 (MIT, https://ionic.io/ionicons), the set the app draws on Android.
export interface IconGlyph { sf: string; ion: string; svg: string }
export const ICONS: Record<string, IconGlyph> = ${JSON.stringify(svgs, null, 2)};
`);
console.error(`icons=${Object.keys(svgs).length} of ${Object.keys(icons).length}`);
